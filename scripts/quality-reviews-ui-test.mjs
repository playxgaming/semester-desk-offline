import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch()
try {
  const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
  const page = await context.newPage(), base = process.env.APP_URL || 'http://127.0.0.1:4173'
  const errors = [], aiCalls = []
  page.on('pageerror', e => errors.push(e.message))
  page.on('request', r => { if (/\/api\/(generate|solve|scan|chat|notes)/.test(r.url())) aiCalls.push(r.url()) })
  await page.goto(base)
  const onboarding = page.getByRole('dialog', { name: 'Set up Semester Desk' })
  await onboarding.getByRole('button', { name: 'Skip', exact: true }).click()
  await onboarding.waitFor({ state: 'hidden' })
  // This browser context is disposable. Never connect this fixture to the user's browser.
  await page.evaluate(async () => {
    const db = await new Promise((resolve, reject) => { const r = indexedDB.open('semester-desk'); r.onsuccess = () => resolve(r.result); r.onerror = () => reject(r.error) })
    const tx = db.transaction([...db.objectStoreNames], 'readwrite')
    for (const name of db.objectStoreNames) if (name !== 'profiles') tx.objectStore(name).clear()
    const base = { user_id: null, updated_at: new Date().toISOString(), deleted_at: null }
    tx.objectStore('notes').put({ ...base, id: 'quality-note', course_id: null, topic_id: null, title: 'Pilot matrix note', body_md: 'A matrix has rows and columns. $2 \\times 3$', pinned: false })
    tx.objectStore('courses').put({ ...base, id: 'quality-course', code: 'MATH101', name: 'Pilot algebra', credits: 3, colour: '#3358CC', instructor: '', target_grade: 80, attendance_threshold: .75, archived: false, semester: 'Pilot' })
    tx.objectStore('course_documents').put({ ...base, id: 'quality-document', course_id: 'quality-course', title: 'Pilot OCR source', kind: 'reference', body_text: 'Matrices and determinants', imported_at: base.updated_at, extraction: 'ocr', pages: [{ number: 1, text: 'Matrices and determinants' }] })
    await new Promise((resolve, reject) => { tx.oncomplete = resolve; tx.onerror = () => reject(tx.error) }); db.close()
  })
  await page.goto(`${base}/#/pilot?item=note%3Aquality-note`); await page.reload()
  await page.getByRole('heading', { level: 1, name: 'Quality reviews' }).waitFor()
  await page.getByRole('button', { name: 'Review this content' }).waitFor()
  await page.evaluate(async () => { await Promise.race([navigator.serviceWorker.ready, new Promise((_, reject) => setTimeout(() => reject(new Error('Offline cache timeout')), 55000))]) })
  await context.setOffline(true)
  await page.reload()
  await page.getByRole('button', { name: 'Review this content' }).click()
  const dialog = page.getByRole('dialog', { name: 'Review course content' })
  await dialog.getByLabel('Verdict', { exact: true }).selectOption('usable')
  await dialog.getByRole('button', { name: 'Save quality review' }).click()
  await dialog.getByRole('alert').waitFor()
  for (const label of ['Facts, numbers and equations checked', 'Required topics covered; gaps identified', 'Text, layout and equations readable', 'Compared with original course material']) await dialog.getByLabel(label, { exact: true }).selectOption('pass')
  await dialog.getByRole('button', { name: 'Save quality review' }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByText('Matches current content', { exact: true }).waitFor()
  await page.reload()
  await page.getByText('Matches current content', { exact: true }).waitFor()
  await page.getByRole('link', { name: 'Open original item' }).click()
  await page.getByRole('heading', { level: 1, name: 'Notes' }).waitFor()
  const edit = page.getByRole('button', { name: 'Edit', exact: true })
  await edit.click()
  const textarea = page.getByLabel('Note body', { exact: true })
  await textarea.fill('Edited matrix note needs a verified worked example.')
  await page.getByRole('link', { name: 'Review note quality' }).click()
  await page.getByText('Changed since review', { exact: true }).first().waitFor()
  await page.getByRole('button', { name: 'Review this content' }).click()
  await dialog.getByLabel('Issues and corrections').fill('Missing worked example — compare with lecture notes.')
  await dialog.getByRole('button', { name: 'Save quality review' }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('heading', { name: 'Review history (2)' }).waitFor()
  await page.getByText('Older content — see saved snapshot', { exact: true }).waitFor()
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Export review report' }).click()
  const report = await download, stream = await report.createReadStream(), chunks = []
  for await (const chunk of stream) chunks.push(chunk)
  const parsed = JSON.parse(Buffer.concat(chunks).toString())
  assert.equal(parsed.reviews.length, 2)
  assert.equal(parsed.items.find(i => i.id === 'quality-note').status, 'Needs changes')
  assert.ok(parsed.reviews.some(r => r.snapshot.body.includes('A matrix has rows')))
  await page.getByLabel('Show items', { exact: true }).selectOption('generated')
  await page.getByRole('heading', { name: 'Pilot OCR source', exact: true }).waitFor()
  assert.equal(await page.getByRole('heading', { name: 'Pilot matrix note', exact: true }).count(), 1, 'Only the selected detail, not the filtered list, retains the manual note')
  await page.getByRole('button', { name: 'Inspect item', exact: true }).click()
  await page.getByRole('button', { name: 'Review this content' }).click()
  await dialog.getByLabel('Issues and corrections').fill('Compare every extracted row with the original photo.')
  await dialog.getByRole('button', { name: 'Save quality review' }).click()
  await dialog.waitFor({ state: 'hidden' })
  await page.getByRole('heading', { name: 'Review history (1)' }).waitFor()
  await page.getByText('Exact reviewed content', { exact: true }).click()
  const savedContent = page.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^Exact reviewed content$/ }) }).locator(':scope > div > pre')
  await savedContent.waitFor()
  assert.equal(await savedContent.textContent(), 'Matrices and determinants')
  await page.setViewportSize({ width: 360, height: 800 })
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false, 'Review page must fit a narrow phone')
  assert.deepEqual(errors, []); assert.deepEqual(aiCalls, [])
  console.log('PASS offline mobile review validation, reload, actual note edit, stale history, report export, OCR review and 360px layout; no AI calls')
} finally { await browser.close() }
